library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use IEEE.numeric_std.all;
use ieee.std_logic_unsigned.all;

entity Ins_mem is
    Port(address:in STD_LOGIC_VECTOR(15 downto 0);
         inst: out STD_LOGIC_VECTOR(31 downto 0));
end Ins_mem;

architecture Behavioral of Ins_mem is
type arr_rom is array(0 to 65535) of STD_LOGIC_VECTOR(7 downto 0);
constant rom: arr_rom :=(

     "00000000","00000000","00000000","00000000",
        "00000000","00010010","10000010","10010011",         -- addi x5,x5,1       
        "00000000","00010010","10000010","10010011",         -- addi x5,x5,1       
        "01000000","01110010","10000001","10110011",         --sub x3, x7, x5       
        "00000000","01110011","01110010","10110011",         --and x5, x6, x7
        "00000000","00000011","01110010","10010011",         --andi x5, x6, 0
        "00000000","01110011","01000010","10110011",         --xor x5, x6, x7
        "00000000","01110011","01000010","10010011",         --xori x5, x6, 7
        "00000000","01110011","01100010","10110011",         --or x5, x6, x7
        "00000000","01110011","01100010","10010011",         --ori x5, x6, 7
        "00000000","01110011","00010010","10110011",         --sll x5, x6, x7
        "00000000","01110011","01010010","10110011",         --srl x5, x6, x7    
        "00000000","01110011","00100010","10110011",         --slt x5, x6, x7   
        "00000000","00110001","00000010","10100011",         --sb x3, 5(x2) 
        "00000000","01010001","00100001","10100011",         --sw x5, 3(x2) 
        "00000000","01010001","00000001","00000011",         --lb x2, 5(x3) 
        "00000000","00110001","10100011","00000011",         --lw x4, 5(x3)
        "00000000","00110000","00000001","00010011",         
        "00000000","00010100","00000100","00010011",        -- addi x8,x8,1                     
        "11111110","10000001","00011100","11100011", 
        
        
        -- Fibonacci
        
               "00000000","00000000","11110000","10010011",   
               "00000000","00000001","01110001","00010011",   
               "00000000","00000001","11110001","10010011",    
               "00000000","00000010","01110010","00010011",    
               "00000000","00000010","11110010","10010011",    
               "00000000","00000011","11110011","10010011",    
               "00000000","00010011","10000011","10010011",    
               "00000000","00010001","10000001","10010011",    
               "00000000","01010000","10000000","10010011",   
               "00000000","00000100","01110100","00010011",    
               "00000000","00000100","00000100","00010011",    
               "00000000","01110100","10000100","10010011",    
               "00000000","01110010","11000110","01100011",    
               "00000000","00000010","10000010","00010011",       
               "00000001","00000000","00000000","01101111",    
               "00000000","00110001","00000010","00110011",    
               "00000000","00000001","10000001","00010011",    
               "00000000","00000010","00000001","10010011",    
               "00000000","01000100","00000000","00100011",    
               "00000000","00010100","00000100","00010011",    
               "00000000","00010010","10000010","10010011",    
               "11111010","10010100","00000110","11100011",    
               "11111100","00010010","11001100","11100011",    
               others => X"00"
           );
begin
           inst <= ROM(conv_integer(Address)) & ROM(conv_integer(Address + 1)) &
                   ROM(conv_integer(Address + 2)) & ROM(conv_integer(Address + 3)); 
                   -- converts address to integer and then goes upto 4 rounds to 
                   --fetch 32 bits in total from the array


end Behavioral;
